def main():
    # Load data from CSV file
    # Assuming the CSV has columns 'text' and 'label'
    df = pd.read_csv('/content/Dataset.csv',encoding='latin-1')

    # Preprocess the text
    df['processed_text'] = df['Text'].apply(preprocess_text)

    # Encode labels
    label_encoder = LabelEncoder()
    df['encoded_label'] = label_encoder.fit_transform(df['Label'])

    # Split the data
    train_df, test_df = train_test_split(df, test_size=0.2, random_state=42, stratify=df['encoded_label'])

    # Load TinyBERT tokenizer and model
    tokenizer = AutoTokenizer.from_pretrained("prajjwal1/bert-tiny")
    bert_model = AutoModel.from_pretrained("prajjwal1/bert-tiny")

    # Create datasets
    train_dataset = TextClassificationDataset(
        texts=train_df['processed_text'].tolist(),
        labels=train_df['encoded_label'].tolist(),
        tokenizer=tokenizer
    )

    test_dataset = TextClassificationDataset(
        texts=test_df['processed_text'].tolist(),
        labels=test_df['encoded_label'].tolist(),
        tokenizer=tokenizer
    )

    # Create data loaders
    train_loader = DataLoader(train_dataset, batch_size=16, shuffle=True)
    test_loader = DataLoader(test_dataset, batch_size=16)

    # Initialize model
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = TextClassifier(
        bert_model=bert_model,
        hidden_dim=128,
        output_dim=len(label_encoder.classes_)
    ).to(device)

    # Define loss function and optimizer
    criterion = nn.CrossEntropyLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=0.001)

    # Training loop
    num_epochs = 10
    for epoch in range(num_epochs):
        model.train()
        train_loss = 0
        correct_preds = 0
        total_preds = 0

        for batch in train_loader:
            # Move batch to device
            input_ids = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            labels = batch['label'].to(device)

            # Forward pass
            optimizer.zero_grad()
            outputs = model(input_ids=input_ids, attention_mask=attention_mask)

            # Calculate loss
            loss = criterion(outputs, labels)
            train_loss += loss.item()

            # Backward pass and optimize
            loss.backward()
            optimizer.step()

            # Calculate accuracy
            _, predicted = torch.max(outputs.data, 1)
            total_preds += labels.size(0)
            correct_preds += (predicted == labels).sum().item()

        train_accuracy = correct_preds / total_preds
        train_loss /= len(train_loader)

        print(f'Epoch {epoch+1}/{num_epochs}, Loss: {train_loss:.4f}, Accuracy: {train_accuracy:.4f}')

    # Evaluation
    model.eval()
    test_loss = 0
    correct_preds = 0
    total_preds = 0

    with torch.no_grad():
        for batch in test_loader:
            input_ids = batch['input_ids'].to(device)
            attention_mask = batch['attention_mask'].to(device)
            labels = batch['label'].to(device)

            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            loss = criterion(outputs, labels)
            test_loss += loss.item()

            _, predicted = torch.max(outputs.data, 1)
            total_preds += labels.size(0)
            correct_preds += (predicted == labels).sum().item()

    test_accuracy = correct_preds / total_preds
    test_loss /= len(test_loader)

    print(f'Test Loss: {test_loss:.4f}, Test Accuracy: {test_accuracy:.4f}')

    # Save the model
    torch.save(model.state_dict(), 'tinybert_lstm_classifier.pt')

    # Function to predict on new text
    def predict(text):
        # Preprocess
        processed_text = preprocess_text(text)

        # Tokenize
        encoding = tokenizer(
            processed_text,
            truncation=True,
            padding='max_length',
            max_length=128,
            return_tensors='pt'
        )

        # Move to device
        input_ids = encoding['input_ids'].to(device)
        attention_mask = encoding['attention_mask'].to(device)

        # Get prediction
        model.eval()
        with torch.no_grad():
            outputs = model(input_ids=input_ids, attention_mask=attention_mask)
            _, predicted = torch.max(outputs.data, 1)

        # Decode prediction
        predicted_label = label_encoder.inverse_transform([predicted.item()])[0]

        return predicted_label

    # Example usage
    sample_text = "This is a sample text for classification."
    predicted_label = predict(sample_text)
    print(f"Predicted class for '{sample_text}': {predicted_label}")

if __name__ == "__main__":
    main()

